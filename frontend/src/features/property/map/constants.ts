/**
 * 지도 레벨별 타일 크기 — 10^-BBOX_PRECISION 도(0.0001도) 단위. 위도 · 경도 축마다 따로 둔다(경도 = 위도 × 2).
 * 표시 영역을 이 크기의 배수로 밖으로 넓힌다 — min은 내림, max는 올림 (kakao-map 4장).
 * 같은 지역 · 같은 레벨이면 사용자 · 기기 · 미세한 이동과 무관하게 같은 영역이 되어 서버 응답 캐시가 적중한다.
 *
 * 근거(실측 2026-10-05, 운영 Chrome 1920×889 · 지도 1474×677, 중심 서울시청 37.5665 · 126.978,
 * 같은 크기의 숨은 kakao.maps.Map 레벨별 getBounds):
 * - 해상도는 레벨 3에서 약 1 m/px이고 레벨마다 두 배다 — 1474 px → 경도 0.01668도 = 1.0 m/px.
 *   화면 폭(도)도 레벨마다 정확히 두 배라 타일도 레벨마다 두 배로 둔다.
 * - 같은 도 값을 위도 · 경도에 쓰면 위도에 너무 크다 — 화면은 위도 폭이 경도 폭의 약 0.37배다
 *   (지도 677 / 1474 px × 경도 1도 88.3 km / 위도 1도 111 km). 예전 같은 값(레벨 7 0.2048도)은
 *   레벨 7 요청이 화면의 위도 2.1배 · 경도 1.15배였다.
 * - 지금 크기에서 이 화면이 덮는 타일은 위도 2 ~ 3(요청이 화면의 1.05 ~ 1.57배) · 경도 3 ~ 4(1.15 ~ 1.53배)다.
 *   레벨마다 비율이 같아 전 레벨에서 같다. 묶음 격자의 행 · 열은 맞춘 영역의 타일 수로 정한다 — 아래 「묶음 격자」.
 * - 대가: 요청 영역이 화면에 가까워져 다른 사용자와 같은 영역이 될 확률(서버 캐시 적중)이 낮아진다.
 *   같은 사용자의 작은 이동은 여전히 같은 타일 안이라 적중한다.
 * - 모바일 폭은 미실측이다. 해상도는 화면 크기와 무관하므로 덮는 타일 수만 줄어든다.
 *
 * | 레벨 | 위도 단위 | 위도(도) | 경도 단위 | 경도(도) | 실측 화면 폭 위도 × 경도(도) |
 * | --- | --- | --- | --- | --- | --- |
 * | 1 | 8 | 0.0008 | 16 | 0.0016 | 0.00153 × 0.00417 |
 * | 2 | 16 | 0.0016 | 32 | 0.0032 | 0.00305 × 0.00834 |
 * | 3 | 32 | 0.0032 | 64 | 0.0064 | 0.0061 × 0.01668 |
 * | 4 | 64 | 0.0064 | 128 | 0.0128 | 0.01221 × 0.03336 |
 * | 5 | 128 | 0.0128 | 256 | 0.0256 | 0.02441 × 0.06673 |
 * | 6 | 256 | 0.0256 | 512 | 0.0512 | 0.04882 × 0.13346 |
 * | 7 | 512 | 0.0512 | 1,024 | 0.1024 | 0.09765 × 0.26692 |
 * | 8 | 1,024 | 0.1024 | 2,048 | 0.2048 | 0.19529 × 0.53384 |
 * | 9 | 2,048 | 0.2048 | 4,096 | 0.4096 | 0.39057 × 1.06767 |
 * | 10 ~ 14 | 두 배씩 | | 두 배씩 | | 서울 단계(묶음 조회 없음) · setMaxLevel 위 |
 *
 * 단위를 전 레벨 정수로 둔 것은 배수 계산이 부동소수 오차 없이 소수 4자리로 끝나게 하려는 것이다
 * (가장 작은 레벨 1 위도도 8 단위 = 0.0008도). 표 밖 레벨은 가장 가까운 끝 값을 쓴다.
 */
