-- 매물 · 시세 갱신 배치(RISK-08) — 시세 금액이 바뀌어 재분석을 기다리는 매물을 표시한다.
--
-- 판정 단계가 재분석 대상을 적재 단계가 메모리에 모은 식별자 목록이 아니라 DB 에서 식별자 커서로 읽게 한다. 2026-09-30 운영
-- 회차에서 적재 단계(25구, 신규 23만여 건)가 끝난 직후 컨테이너가 메모리 상한을 넘어 종료됐다. 회차 동안 쌓이는 식별자 목록을
-- 없애는 것이 이 컬럼의 목적이다.
--
--   · 적재 쓰기 서비스가 시세 금액이 바뀐 매물에 TRUE 로 세운다. 기준일 · 산출 근거만 바뀐 갱신은 세우지 않는다 — 판정
--     입력이 그대로다.
--   · 갱신 배치의 판정 단계가 그 매물의 판정을 마치면 FALSE 로 내린다. 판정이 실패하거나 락 경합으로 건너뛰면 그대로 남아 다음
--     회차가 다시 잡는다.
--
-- 시각 비교(시세 변경 시각 > 최신 판정 시각)로 두지 않은 이유 — 판정은 결론(등급 · 3사 가입 · 전세가율)이 같으면 새 행을 남기지
-- 않는다. 시세가 바뀌어도 결론이 같은 매물은 최신 판정 시각이 그대로라, 시각 비교로는 매 회차 끝없이 재분석 대상이 된다.
--
-- 부분 인덱스 — 재분석 대기 매물은 전체의 일부이고 판정이 끝나면 빠진다. 대기 매물만 식별자 순으로 담아 판정 단계의 첫 갈래 조회가
-- 전체 매물을 훑지 않게 한다. 실행 계획은 운영 규모 더미로 확인하지 않았다(미검증).
ALTER TABLE property
    ADD COLUMN is_reanalysis_pending BOOLEAN NOT NULL DEFAULT FALSE;

CREATE INDEX ix_property_reanalysis_pending ON property (property_id) WHERE is_reanalysis_pending;
