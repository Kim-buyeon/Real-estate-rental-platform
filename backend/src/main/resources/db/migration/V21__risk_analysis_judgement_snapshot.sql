-- 저장된 판정 반환(RISK-01 · #399) — 최신 분석 행에 응답 근거와 그때 쓴 판정 기준의 지문을 함께 둔다.
--
-- 위험도 조회 · 대출 한도 조회가 요청마다 판정 전체(수집 확인 · 등기 · 대장 · 기준표 읽기 · 판정)를 다시 돌렸다. 2026-10-04
-- 부하 시험(#390)에서 요청당 SQL 이 위험도 17 · 대출 22 였다. 판정 결론(등급 · 3사 가입 · 전세가율)만
-- 담는 지금 행으로는 응답을 다시 만들 수 없다 — 기관별 위배 조건 · 보증한도 · 보증료 · 정합 결과가 없다. 근거를 함께 적어 두고,
-- 판정 입력이 그대로인 동안은 저장된 근거를 돌려준다.
--
--   · judgement_snapshot — 응답 근거 JSON. 시세 · 시세 구분 · 기준일 · 분석 시각은 넣지 않는다 — 앞의 셋은 매물에서, 분석 시각은
--     이 행의 analyzed_at 에서 읽는다. 앱이 직렬화한 문자열을 그대로 둔다(TEXT). JSONB 로 두지 않은 이유 — SQL 로 근거를 질의하지
--     않아 이점이 없고, Jackson 3 과 Hibernate JSON 매핑 조합을 새로 검증해야 한다.
--   · criteria_fingerprint — 판정에 쓴 기준표 값 · 대장 연동 모드의 SHA-256(16진 64자). 기준이 바뀌면 지문이 달라져 다음 조회가
--     다시 판정한다. 기준 변경 때 전체 매물을 다시 판정하지 않는 것이 이 열의 목적이다.
--
-- 둘 다 NULL 허용이다. 기존 행은 NULL 이고, 근거가 없는 최신 행은 다음 조회가 판정해 채운다 — 값을 채우는 이행을 두지 않는다
-- (근거는 판정을 다시 돌려야만 나온다). 이력으로 내려간 행은 계속 NULL 일 수 있다.
--
-- 열 추가만이라 표를 다시 쓰지 않는다(PostgreSQL 11 이상, 기본값 없는 NULL 열). lock_timeout 5s 는 V19 와 같은 이유다 — 운영
-- 기본값은 0(무한 대기)이고, ALTER TABLE 은 짧게나마 표 잠금을 잡으므로 잠금 대기가 길면 기다리지 않고 실패시켜 배포를 멈춘다.

SET LOCAL lock_timeout = '5s';

ALTER TABLE risk_analysis
    ADD COLUMN judgement_snapshot TEXT NULL,
    ADD COLUMN criteria_fingerprint VARCHAR(64) NULL;
